<#
.SYNOPSIS
    Checks that every neutral resx of a TcOpen library has all keys translated in the predefined cultures.

.DESCRIPTION
    Scans <LibraryPath>\src for neutral Properties\Localizations.resx (PLC texts generated by the Vortex compiler)
    and Properties\strings.resx (hand-made WPF texts), skipping bin/obj. For each culture it reports:
      MISSING FILE  - culture resx does not exist
      MISSING       - key in neutral, not in culture            (error)
      STALE         - key in culture, not in neutral            (error)
      SAME          - culture value equals the neutral value    (warning only; may be a legitimate term)
    Exit code 1 when any error was found.

.EXAMPLE
    powershell -File .claude\skills\tco-vendor-component\scripts\Test-TcoLocalization.ps1 -LibraryPath src\TcoTemplate
#>
param(
    [Parameter(Mandatory = $true)]
    [string]$LibraryPath,
    [string[]]$Cultures = @('cs-CZ', 'de-DE', 'es-ES', 'sk-SK'),
    [switch]$NoWarnings
)

function Read-Resx([string]$path) {
    $xml = New-Object System.Xml.XmlDocument
    $xml.Load($path)
    $result = [ordered]@{}
    foreach ($node in $xml.SelectNodes('/root/data')) {
        # resources only: skip file references / non-string types
        if ($node.GetAttribute('type') -or $node.GetAttribute('mimetype')) { continue }
        $valueNode = $node.SelectSingleNode('value')
        $result[$node.GetAttribute('name')] = if ($valueNode) { $valueNode.InnerText } else { '' }
    }
    return $result
}

$srcPath = Join-Path $LibraryPath 'src'
if (-not (Test-Path $srcPath)) { $srcPath = $LibraryPath }

$neutralFiles = Get-ChildItem -Path $srcPath -Recurse -File -Include 'Localizations.resx', 'strings.resx' |
    Where-Object { $_.FullName -notmatch '\\(bin|obj)\\' -and $_.Directory.Name -eq 'Properties' }

if (-not $neutralFiles) {
    Write-Host "No neutral Localizations.resx / strings.resx found under $srcPath"
    exit 1
}

$errors = 0
$warnings = 0

foreach ($neutral in $neutralFiles) {
    $relative = $neutral.FullName.Substring((Resolve-Path $LibraryPath).Path.Length).TrimStart('\')
    Write-Host ""
    Write-Host "== $relative"
    $neutralData = Read-Resx $neutral.FullName
    $baseName = [System.IO.Path]::GetFileNameWithoutExtension($neutral.Name)

    foreach ($culture in $Cultures) {
        # culture file names are not consistently cased (e.g. strings.sk-Sk.resx)
        $cultureFile = Get-ChildItem -Path $neutral.DirectoryName -File |
            Where-Object { $_.Name -ieq "$baseName.$culture.resx" } | Select-Object -First 1

        if (-not $cultureFile) {
            Write-Host "   [$culture] MISSING FILE $baseName.$culture.resx"
            $errors++
            continue
        }

        $cultureData = Read-Resx $cultureFile.FullName
        $missing = @($neutralData.Keys | Where-Object { -not $cultureData.Contains($_) })
        $stale = @($cultureData.Keys | Where-Object { -not $neutralData.Contains($_) })
        $same = @($neutralData.Keys | Where-Object { $cultureData.Contains($_) -and $neutralData[$_] -ne '' -and $cultureData[$_] -ceq $neutralData[$_] })

        foreach ($key in $missing) { Write-Host "   [$culture] MISSING $key = '$($neutralData[$key])'" }
        foreach ($key in $stale) { Write-Host "   [$culture] STALE   $key" }
        if (-not $NoWarnings) {
            foreach ($key in $same) { Write-Host "   [$culture] SAME    $key = '$($neutralData[$key])'" }
        }
        $errors += $missing.Count + $stale.Count
        $warnings += $same.Count

        if ($missing.Count + $stale.Count -eq 0) {
            Write-Host "   [$culture] OK ($($cultureData.Count) keys)"
        }
    }
}

Write-Host ""
Write-Host "Errors: $errors  Warnings (SAME): $warnings"
if ($errors -gt 0) { exit 1 } else { exit 0 }
